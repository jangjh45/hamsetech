-- 적재함 프리셋. 예전에는 프론트엔드 상수였고, 이제 관리자가 화면에서 고친다.
-- 시나리오는 치수 숫자를 그대로 저장하므로 프리셋을 바꾸거나 지워도 저장된 시나리오는 바뀌지 않는다.
CREATE TABLE truck_presets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       varchar(50) NOT NULL,
    width       integer NOT NULL CHECK (width > 0),
    height      integer NOT NULL CHECK (height > 0),
    sort_order  integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at  timestamp(6) without time zone NOT NULL,
    updated_at  timestamp(6) without time zone NOT NULL,
    CONSTRAINT ux_truck_presets_label UNIQUE (label)
);

-- 초기 데이터는 기존 화면 상수와 같은 값이다. 이미 행이 있으면 다시 넣지 않는다.
INSERT INTO truck_presets (label, width, height, sort_order, created_at, updated_at)
SELECT v.label, v.width, v.height, v.sort_order, now(), now()
FROM (VALUES
    ('1톤 카고', 2830, 1630, 0),
    ('2.5톤 카고', 4300, 1850, 1),
    ('5톤 카고', 6200, 2300, 2),
    ('5톤 장축', 7400, 2200, 3)
) AS v (label, width, height, sort_order)
WHERE NOT EXISTS (SELECT 1 FROM truck_presets);
